CREATE TABLE historico_links (
  uuid UUID NOT NULL,
  pure_id BIGINT NOT NULL,
  link_type VARCHAR(50) NOT NULL,
  url VARCHAR(255) NOT NULL,
  description VARCHAR(100) DEFAULT NULL,
  PRIMARY KEY (uuid, pure_id),
  CONSTRAINT fk_historico_links_historico
    FOREIGN KEY (uuid) REFERENCES historico(uuid)
    ON DELETE CASCADE,
  CONSTRAINT ck_historico_links_pure_id
    CHECK (pure_id > 0),
  CONSTRAINT ck_historico_links_url
    CHECK (url LIKE 'http%')
